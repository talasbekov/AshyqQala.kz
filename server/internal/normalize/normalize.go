// Package normalize — чистая сигнатура нормализации к каноническому БИН (Story 1.10). Без store/IO/времени.
// Содержательная нормализация наименований→БИН (варианты написания, словарь, auto/manual/conflict) —
// Story 2.3; здесь — только сигнатура-контракт ядра.
package normalize

import "strings"

// BIN — канонический бизнес-идентификатор организации (12 цифр в проде). Тип-контракт ядра.
type BIN string

// Normalize — чистая функция приведения сырого идентификатора/написания к канонической форме.
// Каркас: тримминг + схлопывание внутренних пробелов (детерминированно). Реальная нормализация — Story 2.3.
func Normalize(raw string) BIN {
	return BIN(strings.Join(strings.Fields(raw), " "))
}
